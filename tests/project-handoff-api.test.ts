const requestChoice = (category: string, contextHash: string) => new Request("http://localhost/handoff", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ category, contextHash }) });
it("choix catégorie API : droits serveur, conflit, isolation, sauvegarde sans travail payant ni thème modifié", async () => {
  vi.stubGlobal("fetch", () => { throw Error("Réseau interdit"); });
  const f = await fixture(); initializeSynthetic(f.pid, f.input);
  current = { id: f.uid, role: "client" }; const ctx = { params: Promise.resolve({ id: f.pid }) };
  const original = loadProject(f.pid), data = await (await GET(new Request("http://localhost/handoff"), ctx)).json();
  const accepted = await POST(requestChoice("ecommerce", data.categoryContextHash), ctx);
  expect(accepted.status).toBe(200); expect((await accepted.json()).category).toMatchObject({ category: "ecommerce", status: "recommended" });
  expect(categoryForProject(loadProject(f.pid), f.input).explicitChoice?.category).toBe("ecommerce");
  expect(loadProject(f.pid).storeType).toBe(original.storeType);
  expect(all("SELECT id FROM jobs WHERE project_id=?", f.pid)).toEqual([]); expect(all("SELECT id FROM theme_versions WHERE project_id=?", f.pid)).toEqual([]);
  expect((await POST(requestChoice("services", data.categoryContextHash), ctx)).status).toBe(400);
  expect((await POST(requestChoice("specialized", "outdated-context-hash"), ctx)).status).toBe(409);
  current = await createUser(`handoff-denied-${crypto.randomUUID()}@example.test`, "motdepasse-test", "Autre compte");
  expect((await POST(requestChoice("ecommerce", data.categoryContextHash), ctx)).status).toBe(404);
  current = { id: f.uid, role: "client" };
  run("UPDATE subscriptions SET status='canceled' WHERE user_id=?", f.uid);
  expect((await POST(requestChoice("specialized", data.categoryContextHash), ctx)).status).toBe(402);
});
it("changement de catégorie après rédaction : références actives requalifiées localement, textes/médias et choix historique conservés", async () => {
  vi.stubGlobal("fetch", () => { throw Error("Réseau interdit"); });
  const f = await fixture(); initializeSynthetic(f.pid, f.input); validatedBrand(f.pid, f.input);
  current = { id: f.uid, role: "client" }; const ctx = { params: Promise.resolve({ id: f.pid }) };
  const { content, out } = await editorialFixture(f.pid);
  const bound = bindEditorial(content, out, recommendationCatalogue(loadProject(f.pid)));
  bound.recommendation!.selectedId = "theme-historique";
  commitState(f.pid, stateOf(f.pid)!.revision, s => draft(s, "content", bound));
  const before = structuredClone(stateOf(f.pid)!.stages.content!.data);
  const data = await (await GET(new Request("http://localhost/handoff"), ctx)).json();
  const response = await POST(requestChoice("ecommerce", data.categoryContextHash), ctx);
  expect(response.status).toBe(200);
  const after = stateOf(f.pid)!.stages.content!.data;
  expect(after.documents).toEqual(before.documents); expect(after.editorial).toEqual(before.editorial); expect(after.slots).toEqual(before.slots); expect(after.copy).toEqual(before.copy);
  expect(after.recommendation).toMatchObject({ recommendedReferenceId: "orbe", alternativesReferenceIds: [], engineThemeId: null, recommendedId: "", status: "reference_pending", selectedId: "theme-historique" });
  expect(recommendationDataReady(after.recommendation)).toBe(true);
  expect(all("SELECT id FROM ai_calls WHERE project_id=?", f.pid)).toEqual([]); expect(all("SELECT id FROM theme_versions WHERE project_id=?", f.pid)).toEqual([]);
});
